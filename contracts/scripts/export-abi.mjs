// Copies the compiled ABI + bytecode into the web app (src/lib/chain/artifacts.ts).
// Run after `npx hardhat compile`.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const read = (p) => JSON.parse(readFileSync(path.join(root, "artifacts/contracts", p), "utf8"));
const payments = read("PokeCastPayments.sol/PokeCastPayments.json");
const mock = read("test/MockUSDT.sol/MockUSDT.json");

const out = `// Generated by contracts/scripts/export-abi.mjs — do not edit by hand.
export const paymentsAbi = ${JSON.stringify(payments.abi, null, 2)} as const;
export const paymentsBytecode = "${payments.bytecode}" as const;
export const mockUsdtAbi = ${JSON.stringify(mock.abi, null, 2)} as const;
export const mockUsdtBytecode = "${mock.bytecode}" as const;
`;
writeFileSync(path.join(root, "../src/lib/chain/artifacts.ts"), out);
console.log("wrote src/lib/chain/artifacts.ts");
